-- ---------------------------------------------------------------------
-- 1. CREATE TABLE
-- ---------------------------------------------------------------------

-- Tabela independente
CREATE TABLE public.categoria (
    id_categoria        integer      NOT NULL,
    nome_categoria      varchar(50)  NOT NULL,
    descricao_categoria varchar(150),
    CONSTRAINT categoria_pkey PRIMARY KEY (id_categoria),
    CONSTRAINT categoria_nome_unique UNIQUE (nome_categoria)
);

-- Tabela independente
CREATE TABLE public.fabricante (
    id_fabricante   integer      NOT NULL,
    nome_fabricante varchar(50)  NOT NULL,
    pais_fabricante varchar(40),
    CONSTRAINT fabricante_pkey PRIMARY KEY (id_fabricante)
);

-- Tabela independente: usuários do sistema. perfil: 'cliente', 'admin' (funcionário) ou 'ambos' (cliente e funcionário). A senha é guardada como hash (scrypt).
CREATE TABLE public.usuario (
    id_usuario            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_usuario          varchar(80)  NOT NULL,
    email_usuario         varchar(100) NOT NULL UNIQUE,
    senha_hash_usuario    varchar(200) NOT NULL,
    perfil_usuario        varchar(10)  NOT NULL DEFAULT 'cliente',
    data_cadastro_usuario timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    google_id_usuario          varchar(40) UNIQUE,  -- login com Google: identificador (sub) da conta Google vinculada
    token_reset_hash_usuario   varchar(64),     -- recuperação de senha: hash (SHA-256) do token enviado por e-mail
    token_reset_expira_usuario timestamptz,     -- validade do token (1 hora)
    CONSTRAINT usuario_perfil_check CHECK (perfil_usuario IN ('cliente', 'admin', 'ambos'))
);

-- Relacionamento 1:N -> uma categoria tem N periféricos; um fabricante tem N periféricos
CREATE TABLE public.periferico (
    id_periferico                 integer        NOT NULL,
    nome_periferico               varchar(80)    NOT NULL,
    preco_periferico              numeric(10,2)  NOT NULL DEFAULT 0,
    quantidade_estoque_periferico integer        NOT NULL DEFAULT 0,
    id_categoria                  integer        NOT NULL,
    id_fabricante                 integer        NOT NULL,
    CONSTRAINT periferico_pkey PRIMARY KEY (id_periferico),
    CONSTRAINT fk_periferico_categoria  FOREIGN KEY (id_categoria)  REFERENCES public.categoria (id_categoria),
    CONSTRAINT fk_periferico_fabricante FOREIGN KEY (id_fabricante) REFERENCES public.fabricante (id_fabricante),
    CONSTRAINT periferico_preco_check   CHECK (preco_periferico >= 0),
    CONSTRAINT periferico_estoque_check CHECK (quantidade_estoque_periferico >= 0)
);

-- Relacionamento 1:1 -> cada periférico tem no máximo UMA especificação.
-- A PK é também a FK (id_periferico), o que garante a cardinalidade 1:1.
CREATE TABLE public.especificacao (
    id_periferico                integer      NOT NULL,
    conexao_especificacao        varchar(30),
    garantia_meses_especificacao integer      NOT NULL DEFAULT 0,
    peso_gramas_especificacao    integer      NOT NULL DEFAULT 0,
    iluminacao_rgb_especificacao boolean      NOT NULL DEFAULT false,
    detalhes_especificacao       varchar(200),
    CONSTRAINT especificacao_pkey PRIMARY KEY (id_periferico),
    CONSTRAINT fk_especificacao_periferico FOREIGN KEY (id_periferico)
        REFERENCES public.periferico (id_periferico) ON DELETE CASCADE,
    CONSTRAINT especificacao_garantia_check CHECK (garantia_meses_especificacao >= 0),
    CONSTRAINT especificacao_peso_check     CHECK (peso_gramas_especificacao >= 0)
);

-- Relacionamento 1:N -> um usuário faz N pedidos
CREATE TABLE public.pedido (
    id_pedido               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario              integer        NOT NULL,
    data_pedido             timestamp      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status_pedido           varchar(25)    NOT NULL DEFAULT 'pago',
    forma_pagamento_pedido  varchar(20)    NOT NULL,
    endereco_entrega_pedido varchar(150)   NOT NULL,
    valor_total_pedido      numeric(10,2)  NOT NULL DEFAULT 0,
    CONSTRAINT fk_pedido_usuario FOREIGN KEY (id_usuario) REFERENCES public.usuario (id_usuario),
    CONSTRAINT pedido_status_check CHECK (status_pedido IN
        ('aguardando_pagamento', 'pago', 'enviado', 'entregue', 'cancelado', 'devolvido_parcial', 'devolvido')),
    CONSTRAINT pedido_pagamento_check CHECK (forma_pagamento_pedido IN
        ('pix', 'cartao_credito', 'cartao_debito', 'boleto')),
    CONSTRAINT pedido_valor_check CHECK (valor_total_pedido >= 0)
);

-- Relacionamento 1:N -> um pedido tem N itens; um periférico aparece em N itens
-- (esta tabela resolve o N:N entre pedido e periferico). O preço é copiado para o item
-- para o histórico não mudar se o preço do produto mudar depois.
CREATE TABLE public.item_pedido (
    id_item_pedido            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido                 integer       NOT NULL,
    id_periferico             integer       NOT NULL,
    quantidade_item           integer       NOT NULL,
    preco_unitario_item       numeric(10,2) NOT NULL,
    quantidade_devolvida_item integer       NOT NULL DEFAULT 0,
    CONSTRAINT fk_item_pedido FOREIGN KEY (id_pedido) REFERENCES public.pedido (id_pedido) ON DELETE CASCADE,
    CONSTRAINT fk_item_periferico FOREIGN KEY (id_periferico) REFERENCES public.periferico (id_periferico),
    CONSTRAINT item_quantidade_check CHECK (quantidade_item > 0),
    CONSTRAINT item_devolvida_check CHECK (quantidade_devolvida_item >= 0 AND quantidade_devolvida_item <= quantidade_item)
);

-- Relacionamento 1:N -> um item do pedido pode ter N devoluções (parciais).
-- Ex.: comprou 3 mouses e devolveu 1 hoje e 1 amanhã.
CREATE TABLE public.devolucao (
    id_devolucao                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_item_pedido              integer       NOT NULL,
    quantidade_devolucao        integer       NOT NULL,
    motivo_devolucao            varchar(200)  NOT NULL,
    status_devolucao            varchar(15)   NOT NULL DEFAULT 'solicitada',
    data_solicitacao_devolucao  timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_decisao_devolucao      timestamp,
    valor_reembolso_devolucao   numeric(10,2) NOT NULL DEFAULT 0,
    resposta_devolucao          varchar(200),
    CONSTRAINT fk_devolucao_item FOREIGN KEY (id_item_pedido) REFERENCES public.item_pedido (id_item_pedido) ON DELETE CASCADE,
    CONSTRAINT devolucao_quantidade_check CHECK (quantidade_devolucao > 0),
    CONSTRAINT devolucao_status_check CHECK (status_devolucao IN ('solicitada', 'aprovada', 'recusada'))
);

